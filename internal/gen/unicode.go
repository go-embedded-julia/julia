// Package gen writes the files derived from the reference oracle: the
// Unicode tables of the lexer and the golden files of the test suite. The
// command `jloracle regen` runs all of it.
package gen

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

// Oracle is the part of *oracle.Process the generators use.
type Oracle interface {
	Call(op string, args ...string) (string, error)
}

// unicodeProps are the properties the oracle dumps, in its order, with the
// Go identifier of each generated table.
var unicodeProps = []struct{ name, table string }{
	{"idstart", "idStartTable"},
	{"idchar", "idCharTable"},
	{"cat", "categoryTable"},
	{"space", "spaceTable"},
	{"bound", "boundTable"},
	{"width", "widthTable"},
}

type rangeVal struct {
	lo, hi uint32
	v      int
}

// UnicodeTables asks the oracle for its Unicode property dump and returns the
// Go source of internal/unitab/tables_gen.go.
func UnicodeTables(o Oracle, julia string) ([]byte, error) {
	dump, err := o.Call("unicode")
	if err != nil {
		return nil, err
	}
	version, props, err := parseUnicodeDump(dump)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by `jloracle unicode` from julia %s (utf8proc, Unicode %s). DO NOT EDIT.\n\n", julia, version)
	b.WriteString("package unitab\n\n")
	fmt.Fprintf(&b, "// UnicodeVersion is the Unicode version of the reference utf8proc build.\nconst UnicodeVersion = %q\n\n", version)
	for _, p := range unicodeProps {
		rs, ok := props[p.name]
		if !ok {
			return nil, fmt.Errorf("gen: oracle dump has no %q table", p.name)
		}
		// Ranges with value 0 are implicit: lookups of absent code points
		// return 0, so only nonzero runs are stored.
		fmt.Fprintf(&b, "var %s = []rng{\n", p.table)
		for _, r := range rs {
			if r.v != 0 {
				fmt.Fprintf(&b, "\t{0x%x, 0x%x, %d},\n", r.lo, r.hi, r.v)
			}
		}
		b.WriteString("}\n\n")
	}
	return format.Source(b.Bytes())
}

// graphemeSamples are code points of every grapheme bound class and Indic
// conjunct break value: Other, CR, LF, Control, Extend, ZWJ, regional
// indicators, Hangul L/V/T/LV/LVT, SpacingMark, Prepend, Extended
// Pictographic, and Devanagari consonant, virama (linker) and nukta (extend).
// U+0378 is unassigned.
var graphemeSamples = []uint32{
	'a', '\r', '\n', 0x07, 0x0301, 0x200d, 0x1f1e6, 0x1f1e7, 0x1100, 0x1161,
	0x11a8, 0xac00, 0xac01, 0x0903, 0x0600, 0x1f600, 0x0915, 0x094d, 0x093c, 0x00ad,
	0x0378,
}

// GraphemeSequences returns the code point sequences of the grapheme-break
// golden: the sequences of the stateful rules (emoji ZWJ, Indic conjuncts,
// regional indicator pairs), every pair of samples, then pseudo-random
// longer sequences.
func GraphemeSequences() [][]uint32 {
	out := [][]uint32{
		{0x1f600, 0x200d, 0x1f600},
		{0x1f600, 0x0301, 0x200d, 0x1f600},
		{0x1f600, 0x0301, 0x0301, 0x200d, 0x1f600, 0x200d, 0x1f600},
		{0x0915, 0x094d, 0x0915},
		{0x0915, 0x094d, 0x093c, 0x0915},
		{0x0915, 0x093c, 0x094d, 0x0915, 0x094d, 'a'},
		{0x1f1e6, 0x1f1e7, 0x1f1e6, 0x1f1e7, 0x1f1e6},
	}
	for _, a := range graphemeSamples {
		for _, b := range graphemeSamples {
			out = append(out, []uint32{a, b})
		}
	}
	x := uint32(2463534242) // xorshift32, fixed seed: the list is part of the golden
	next := func() uint32 {
		x ^= x << 13
		x ^= x >> 17
		x ^= x << 5
		return x
	}
	for i := 0; i < 1500; i++ {
		n := 3 + int(next()%5)
		seq := make([]uint32, n)
		for j := range seq {
			seq[j] = graphemeSamples[next()%uint32(len(graphemeSamples))]
		}
		out = append(out, seq)
	}
	return out
}

// GraphemeGolden asks the oracle for utf8proc's stateful grapheme breaks of
// every sequence and returns the golden file: one line per sequence,
// "cp,cp,…:b,b,…" with one 0/1 per adjacent pair.
func GraphemeGolden(o Oracle) ([]byte, error) {
	var b bytes.Buffer
	for _, seq := range GraphemeSequences() {
		parts := make([]string, len(seq))
		for i, cp := range seq {
			parts[i] = strconv.FormatUint(uint64(cp), 10)
		}
		cps := strings.Join(parts, ",")
		ans, err := o.Call("graphemebreak", cps)
		if err != nil {
			return nil, err
		}
		b.WriteString(cps + ":" + ans + "\n")
	}
	return b.Bytes(), nil
}

func parseUnicodeDump(dump string) (string, map[string][]rangeVal, error) {
	props := map[string][]rangeVal{}
	version := ""
	cur := ""
	sc := bufio.NewScanner(strings.NewReader(dump))
	for sc.Scan() {
		line := sc.Text()
		switch {
		case strings.HasPrefix(line, "unicode "):
			version = strings.TrimPrefix(line, "unicode ")
		case strings.HasPrefix(line, "prop "):
			cur = strings.TrimPrefix(line, "prop ")
		default:
			f := strings.Fields(line)
			if len(f) != 3 || cur == "" {
				return "", nil, fmt.Errorf("gen: bad unicode dump line %q", line)
			}
			var nums [3]int64
			for i, s := range f {
				n, err := strconv.ParseInt(s, 10, 64)
				if err != nil {
					return "", nil, fmt.Errorf("gen: bad unicode dump line %q", line)
				}
				nums[i] = n
			}
			props[cur] = append(props[cur], rangeVal{uint32(nums[0]), uint32(nums[1]), int(nums[2])})
		}
	}
	if version == "" {
		return "", nil, fmt.Errorf("gen: unicode dump has no version line")
	}
	return version, props, nil
}
